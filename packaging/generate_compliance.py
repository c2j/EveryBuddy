#!/usr/bin/env python3
"""Generate SBOM.json and THIRD_PARTY_NOTICES.md from cargo metadata.

The system GTK stack is listed explicitly because it is not a Cargo package.
Run from the repository root; the output is deterministic.
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORKSPACE = {
    "evobuddy", "eb-api", "eb-plugin-acp-agent", "eb-plugin-composer",
    "eb-plugin-demo-agent", "eb-plugin-nav", "eb-plugin-notices",
}
SYSTEM = [
    ("gtk", "3.24.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/gtk"),
    ("glib", "2.80.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/glib"),
    ("pango", "1.52.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/pango"),
    ("cairo", "1.18.x", "LGPL-2.1-or-later OR MPL-1.1", "https://gitlab.freedesktop.org/cairo/cairo"),
    ("gdk-pixbuf", "2.42.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/gdk-pixbuf"),
    ("atk", "2.52.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/at-spi2-core"),
    ("librsvg", "2.58.x", "LGPL-2.1-or-later", "https://gitlab.gnome.org/GNOME/librsvg"),
]


def main():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1"], cwd=ROOT
    ))
    packages = []
    seen = set()
    for package in meta["packages"]:
        if package["name"] in WORKSPACE:
            continue
        key = (package["name"], package["version"])
        if key in seen:
            continue
        seen.add(key)
        packages.append(package)
    packages.sort(key=lambda p: (p["name"], p["version"]))

    components = [{
        "type": "application",
        "bom-ref": "pkg:cargo/evobuddy@0.5.0",
        "name": "evobuddy",
        "version": "0.5.0",
        "licenses": [{"license": {"id": "MIT"}}],
        "purl": "pkg:cargo/evobuddy@0.5.0",
    }]
    for package in packages:
        licenses = package.get("license") or "NOASSERTION"
        components.append({
            "type": "library",
            "bom-ref": f"pkg:cargo/{package['name']}@{package['version']}",
            "name": package["name"],
            "version": package["version"],
            "licenses": [{"expression": licenses}],
            "purl": f"pkg:cargo/{package['name']}@{package['version']}",
        })
    for name, version, license_expr, url in SYSTEM:
        components.append({
            "type": "library",
            "bom-ref": f"pkg:generic/{name}@{version}",
            "name": name,
            "version": version,
            "licenses": [{"expression": license_expr}],
            "purl": f"pkg:generic/{name}@{version}",
            "externalReferences": [{"type": "website", "url": url}],
        })
    components.append({
        "type": "data",
        "bom-ref": "pkg:generic/evobuddy-assets@1",
        "name": "evobuddy-assets",
        "version": "1",
        "licenses": [{"license": {"id": "MIT"}}],
        "description": "EvoBuddy's own PNG icons and mascot; generated by crates/eb/assets/gen_icons.py",
    })

    bom = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "component": components[0],
            "properties": [
                {"name": "evobuddy:license", "value": "MIT"},
                {"name": "evobuddy:lgpl-source-offer", "value": "docs/lgpl-source-offer.md"},
            ],
        },
        "components": components,
    }
    (ROOT / "SBOM.json").write_text(json.dumps(bom, indent=1, sort_keys=True) + "\n")

    lines = [
        "# Third-party notices",
        "",
        "EvoBuddy itself is MIT-licensed (see `LICENSE`). The self-contained",
        "packages also include the components below. Full license texts are in",
        "`LICENSES/`; the GTK/LGPL source offer is in `docs/lgpl-source-offer.md`.",
        "",
        "## Rust crates",
        "",
        "| Component | Version | License expression |",
        "|---|---|---|",
    ]
    for package in packages:
        lines.append(
            f"| `{package['name']}` | {package['version']} | {package.get('license') or 'NOASSERTION'} |"
        )
    lines += [
        "",
        "## GTK stack (dynamically linked)",
        "",
        "| Component | Version | License | Upstream |",
        "|---|---|---|---|",
    ]
    for name, version, license_expr, url in SYSTEM:
        lines.append(f"| `{name}` | {version} | {license_expr} | {url} |")
    lines += [
        "",
        "## Fonts (Linux bundle)",
        "",
        "- DejaVu Sans — Bitstream Vera license; copied as `share/fonts/licenses/dejavu.txt`.",
        "- WenQuanYi Micro Hei — see `share/fonts/licenses/wqy-microhei.txt`.",
        "",
        "## EvoBuddy artwork",
        "",
        "`crates/eb/assets/icons/*.png` and `mascot.png` are original EvoBuddy",
        "artwork generated by `crates/eb/assets/gen_icons.py`, MIT-licensed.",
        "",
    ]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
